const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
const now = new Date();
const hoursAgo = (h: number) => new Date(now.getTime() - h * HOUR);
const daysAgo = (d: number) => new Date(now.getTime() - d * DAY);

/** Midnight IST of the calendar day `offset` days from today (date-only fields). */
function istDay(offset: number) {
  const ymd = new Date(now.getTime() + offset * DAY).toLocaleDateString("en-CA", { timeZone: "Asia/Kolkata" });
  return new Date(`${ymd}T00:00:00+05:30`);
}

/** A time of day in IST, `offset` days from today. */
function istAt(offset: number, hour: number, minute = 0) {
  return new Date(istDay(offset).getTime() + hour * HOUR + minute * 60 * 1000);
}

/** Builds a one-page PDF so the admin document preview has something real to show. */
function makePdf(title: string, lines: string[]) {
  const esc = (s: string) => s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  const content = [
    "BT",
    "/F1 18 Tf",
    "72 740 Td",
    `(${esc(title)}) Tj`,
    "/F1 11 Tf",
    "0 -30 Td",
    ...lines.flatMap((line) => [`(${esc(line)}) Tj`, "0 -18 Td"]),
    "0 -24 Td",
    "(SAMPLE DOCUMENT - generated by the Readyhire demo seed) Tj",
    "ET",
  ].join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${Buffer.byteLength(content, "latin1")} >>\nstream\n${content}\nendstream`,
  ];
  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((obj, i) => {
    offsets.push(Buffer.byteLength(pdf, "latin1"));
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xref = Buffer.byteLength(pdf, "latin1");
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, "latin1");
}

